        (member_type = 'STANDARD'
            AND estudiante_sk > 0
            AND (id_ra IS NOT NULL OR id_alumno IS NOT NULL)
            AND technical_label IS NULL)
        OR (member_type = 'UNKNOWN'
            AND estudiante_sk = -1
            AND id_ra IS NULL
            AND id_alumno IS NULL
            AND technical_label = 'Desconocido'
            AND source_run_id IS NULL)
        OR (member_type = 'NOT_APPLICABLE'
            AND estudiante_sk = 0
            AND id_ra IS NULL
            AND id_alumno IS NULL
            AND technical_label = 'No aplica'
            AND source_run_id IS NULL)
