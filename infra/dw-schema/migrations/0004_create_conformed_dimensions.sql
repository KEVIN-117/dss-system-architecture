CREATE OR REPLACE FUNCTION dw.touch_dimension_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, dw
AS $$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION dw.protect_technical_dimension_member()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = pg_catalog, dw
AS $$
BEGIN
    IF OLD.member_type <> 'STANDARD' THEN
        RAISE EXCEPTION 'Los miembros técnicos de % no pueden modificarse ni eliminarse', TG_TABLE_NAME
            USING ERRCODE = '55000';
    END IF;

    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
END;
$$;

