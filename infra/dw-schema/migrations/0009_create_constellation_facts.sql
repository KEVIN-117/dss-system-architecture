-- DW-MVP-001: physical fact constellation for admission, coursework and retention.
-- This migration creates facts only; it does not extract OLTP data or execute Hop.

DO $$
BEGIN
    IF to_regclass('etl_control.schema_migration') IS NULL
       OR to_regclass('etl_control.etl_execution') IS NULL
       OR to_regclass('etl_control.academic_period_closure') IS NULL
       OR to_regclass('dw.dim_estudiante') IS NULL
       OR to_regclass('dw.dim_programa') IS NULL
       OR to_regclass('dw.dim_materia') IS NULL
       OR to_regclass('dw.dim_periodo_academico') IS NULL
       OR to_regclass('dw.dim_admision') IS NULL
       OR NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'dw' AND table_name = 'dim_estudiante'
              AND column_name = 'valid_from'
       ) THEN
        RAISE EXCEPTION 'DW-002, DW-003, DW-004, DW-006 y DW-MVP-001/0008 deben estar aplicadas';
    END IF;
END;
$$;

SET ROLE dw_owner;

CREATE TABLE dw.fact_admision (
    fact_admision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_sk BIGINT NOT NULL REFERENCES dw.dim_estudiante (estudiante_sk) ON DELETE RESTRICT,
    programa_sk BIGINT NOT NULL REFERENCES dw.dim_programa (programa_sk) ON DELETE RESTRICT,
    periodo_academico_sk BIGINT NOT NULL REFERENCES dw.dim_periodo_academico (periodo_academico_sk) ON DELETE RESTRICT,
    admision_sk BIGINT NOT NULL REFERENCES dw.dim_admision (admision_sk) ON DELETE RESTRICT,
    id_alumno_origen INTEGER NOT NULL,
    id_programa_origen VARCHAR(3) NOT NULL,
    id_gestion_origen SMALLINT NULL,
    id_periodo_origen SMALLINT NULL,
    conteo_postulacion SMALLINT NOT NULL DEFAULT 1,
    es_admitido BOOLEAN NULL,
    puntaje_examen INTEGER NULL,
    estado_origen CHAR(1) NULL,
    run_id UUID NOT NULL REFERENCES etl_control.etl_execution (run_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT ck_fact_admision_source_program CHECK (btrim(id_programa_origen) <> ''),
    CONSTRAINT ck_fact_admision_source_period CHECK (
        ((id_gestion_origen IS NULL) = (id_periodo_origen IS NULL))
        AND (id_gestion_origen IS NULL
            OR (id_gestion_origen >= 2000 AND id_periodo_origen > 0))
    ),
    CONSTRAINT ck_fact_admision_count CHECK (conteo_postulacion = 1)
);

COMMENT ON TABLE dw.fact_admision IS
    'Una fila por registro de public.postulantes. No se impone unicidad de origen hasta aprobar cardinalidad id_alumno/programa/periodo con DSA/TI.';

CREATE TABLE dw.fact_cursado (
    fact_cursado_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_sk BIGINT NOT NULL REFERENCES dw.dim_estudiante (estudiante_sk) ON DELETE RESTRICT,
    programa_sk BIGINT NOT NULL REFERENCES dw.dim_programa (programa_sk) ON DELETE RESTRICT,
    materia_sk BIGINT NOT NULL REFERENCES dw.dim_materia (materia_sk) ON DELETE RESTRICT,
    periodo_academico_sk BIGINT NOT NULL REFERENCES dw.dim_periodo_academico (periodo_academico_sk) ON DELETE RESTRICT,
    id_matricula_origen INTEGER NOT NULL,
    grupo_degenerado SMALLINT NULL,
    nota_final NUMERIC NULL,
    nota_complementaria NUMERIC NULL,
    nota_examen_mesa NUMERIC NULL,
    nota_parcial_1 NUMERIC NULL,
    nota_parcial_2 NUMERIC NULL,
    nota_parcial_3 NUMERIC NULL,
    nota_parcial_4 NUMERIC NULL,
    estado_origen TEXT NOT NULL,
    es_aprobado BOOLEAN NULL,
    es_reprobado BOOLEAN NULL,
    es_abandono BOOLEAN NULL,
    es_repeticion BOOLEAN NULL,
    conteo_intento SMALLINT NOT NULL DEFAULT 1,
    run_id UUID NOT NULL REFERENCES etl_control.etl_execution (run_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_fact_cursado_id_matricula_origen UNIQUE (id_matricula_origen),
    CONSTRAINT ck_fact_cursado_flags CHECK (
        es_aprobado IS NULL OR es_reprobado IS NULL OR es_aprobado <> es_reprobado
    ),
    CONSTRAINT ck_fact_cursado_count CHECK (conteo_intento = 1)
);

COMMENT ON TABLE dw.fact_cursado IS
    'Una fila por academico.notas_planilla.id_matricula; las notas y flags se agregan solo dentro de este grano.';

CREATE TABLE dw.fact_retencion_desercion (
    fact_retencion_desercion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_sk BIGINT NOT NULL REFERENCES dw.dim_estudiante (estudiante_sk) ON DELETE RESTRICT,
    programa_sk BIGINT NOT NULL REFERENCES dw.dim_programa (programa_sk) ON DELETE RESTRICT,
    periodo_academico_sk BIGINT NOT NULL REFERENCES dw.dim_periodo_academico (periodo_academico_sk) ON DELETE RESTRICT,
    closure_id BIGINT NOT NULL REFERENCES etl_control.academic_period_closure (closure_id) ON DELETE RESTRICT,
    materias_cursadas INTEGER NULL,
    materias_aprobadas INTEGER NULL,
    materias_reprobadas INTEGER NULL,
    materias_arrastradas INTEGER NULL,
    ppa_acumulado NUMERIC NULL,
    resultado_retencion VARCHAR(20) NOT NULL DEFAULT 'NO_EVALUABLE',
    es_desercion BOOLEAN NULL,
    conteo_snapshot SMALLINT NOT NULL DEFAULT 1,
    conteo_evaluable SMALLINT NOT NULL DEFAULT 0,
    conteo_desercion SMALLINT NOT NULL DEFAULT 0,
    run_id UUID NOT NULL REFERENCES etl_control.etl_execution (run_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_fact_retencion_student_program_period UNIQUE (
        estudiante_sk, programa_sk, periodo_academico_sk
    ),
    CONSTRAINT fk_fact_retencion_period_closure FOREIGN KEY (periodo_academico_sk, closure_id)
        REFERENCES dw.dim_periodo_academico (periodo_academico_sk, closure_id) ON DELETE RESTRICT,
    CONSTRAINT ck_fact_retencion_counts CHECK (
        (materias_cursadas IS NULL OR materias_cursadas >= 0)
        AND (materias_aprobadas IS NULL OR materias_aprobadas >= 0)
        AND (materias_reprobadas IS NULL OR materias_reprobadas >= 0)
        AND (materias_arrastradas IS NULL OR materias_arrastradas >= 0)
        AND (conteo_snapshot = 1)
        AND (conteo_evaluable IN (0, 1))
        AND (conteo_desercion IN (0, 1))
        AND conteo_desercion <= conteo_evaluable
    ),
    CONSTRAINT ck_fact_retencion_result CHECK (
        resultado_retencion IN ('RETENIDO', 'DESERTOR', 'NO_EVALUABLE')
    ),
    CONSTRAINT ck_fact_retencion_evaluable_consistency CHECK (
        (resultado_retencion = 'NO_EVALUABLE'
            AND es_desercion IS NULL
            AND conteo_evaluable = 0
            AND conteo_desercion = 0)
        OR (resultado_retencion = 'RETENIDO'
            AND es_desercion = FALSE
            AND conteo_evaluable = 1
            AND conteo_desercion = 0)
        OR (resultado_retencion = 'DESERTOR'
            AND es_desercion = TRUE
            AND conteo_evaluable = 1
            AND conteo_desercion = 1)
    )
);

COMMENT ON TABLE dw.fact_retencion_desercion IS
    'Un snapshot por estudiante, programa y periodo cerrado; NO_EVALUABLE mantiene es_desercion NULL y no ingresa a tasas.';

CREATE INDEX idx_fact_admision_student_period ON dw.fact_admision (estudiante_sk, periodo_academico_sk);
CREATE INDEX idx_fact_admision_program_period ON dw.fact_admision (programa_sk, periodo_academico_sk);
CREATE INDEX idx_fact_admision_source_id ON dw.fact_admision (id_alumno_origen, id_programa_origen, id_gestion_origen, id_periodo_origen);
CREATE INDEX idx_fact_admision_run_id ON dw.fact_admision (run_id);

CREATE INDEX idx_fact_cursado_student_period ON dw.fact_cursado (estudiante_sk, periodo_academico_sk);
CREATE INDEX idx_fact_cursado_program_subject_period ON dw.fact_cursado (programa_sk, materia_sk, periodo_academico_sk);
CREATE INDEX idx_fact_cursado_period_subject ON dw.fact_cursado (periodo_academico_sk, materia_sk);
CREATE INDEX idx_fact_cursado_run_id ON dw.fact_cursado (run_id);

CREATE INDEX idx_fact_retencion_program_period ON dw.fact_retencion_desercion (programa_sk, periodo_academico_sk);
CREATE INDEX idx_fact_retencion_closure ON dw.fact_retencion_desercion (closure_id);
CREATE INDEX idx_fact_retencion_run_id ON dw.fact_retencion_desercion (run_id);

ALTER TABLE dw.fact_admision OWNER TO dw_owner;
ALTER TABLE dw.fact_cursado OWNER TO dw_owner;
ALTER TABLE dw.fact_retencion_desercion OWNER TO dw_owner;

RESET ROLE;

REVOKE ALL ON TABLE dw.fact_admision,
    dw.fact_cursado,
    dw.fact_retencion_desercion FROM PUBLIC;
REVOKE ALL ON SEQUENCE dw.fact_admision_fact_admision_id_seq,
    dw.fact_cursado_fact_cursado_id_seq,
    dw.fact_retencion_desercion_fact_retencion_desercion_id_seq FROM PUBLIC;

GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE dw.fact_admision,
    dw.fact_cursado,
    dw.fact_retencion_desercion TO dw_publisher;
GRANT USAGE, SELECT ON SEQUENCE dw.fact_admision_fact_admision_id_seq,
    dw.fact_cursado_fact_cursado_id_seq,
    dw.fact_retencion_desercion_fact_retencion_desercion_id_seq TO dw_publisher;
GRANT SELECT ON TABLE dw.fact_admision,
    dw.fact_cursado,
    dw.fact_retencion_desercion TO dw_reader, dw_ml_writer;
