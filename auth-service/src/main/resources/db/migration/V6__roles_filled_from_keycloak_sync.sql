-- IAM-004: the local roles table stops being a fixed seed (V4) and is filled by the Keycloak user sync.
-- Any realm role Keycloak sends is stored on first sight, so creating a role in Keycloak never breaks the sync.
-- The four rows seeded by V4 are kept: they are real realm roles and user_roles references them.

-- Keycloak role names can be up to 255 characters.
ALTER TABLE roles ALTER COLUMN name TYPE VARCHAR(255);

-- Synced roles may have no description.
ALTER TABLE roles ALTER COLUMN description DROP NOT NULL;

-- New roles get their id from an identity sequence that starts after the seeded ids.
ALTER TABLE roles ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('roles', 'id'), COALESCE((SELECT MAX(id) FROM roles), 0) + 1, false);
